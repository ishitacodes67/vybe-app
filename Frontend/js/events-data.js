function getEventById(id) {

    return VYBE_EVENTS.find(
        event => event.id === id
    ) || null;

}


function eventDate(event) {

    return new Date(
        `${event.date}T23:59:59`
    );

}


function getUpcomingEvents() {

    return [...VYBE_EVENTS]
        .filter(
            event =>
                eventDate(event) >= new Date()
        )
        .sort(
            (a, b) =>
                a.date.localeCompare(b.date)
        );

}


function getPastEvents() {

    return [...VYBE_EVENTS]
        .filter(
            event =>
                eventDate(event) < new Date()
        )
        .sort(
            (a, b) =>
                b.date.localeCompare(a.date)
        );

}


function getRecommendedEvents(user) {

    const interests =
        (user?.interests || [])
            .map(
                item =>
                    item.toLowerCase()
            );


    const goals =
        (user?.goals || [])
            .map(
                item =>
                    item.toLowerCase()
            );


    return getUpcomingEvents()

        .map(event => {

            const searchable =
                `
                ${event.category}
                ${event.tags.join(" ")}
                ${event.title}
                ${event.description}
                `.toLowerCase();


            let score = 0;


            interests.forEach(
                interest => {

                    if (
                        searchable.includes(
                            interest
                        )
                    ) {

                        score += 5;

                    }

                }
            );


            goals.forEach(
                goal => {

                    const terms =
                        goal.split(/\s+/);


                    if (
                        terms.some(
                            term =>
                                term.length > 3 &&
                                searchable.includes(term)
                        )
                    ) {

                        score += 1;

                    }

                }
            );


            return {
                ...event,
                recommendationScore:
                    score
            };

        })


        .sort(
            (a, b) =>
                b.recommendationScore -
                    a.recommendationScore ||
                a.date.localeCompare(
                    b.date
                )
        );

}


function formatEventDate(date) {

    return new Date(
        `${date}T12:00:00`
    ).toLocaleDateString(
        "en-IN",
        {
            weekday: "short",
            day: "numeric",
            month: "short",
            year: "numeric"
        }
    );

}


function formatPrice(price) {

    return Number(price) === 0
        ? "Free"
        : `₹${Number(price).toLocaleString(
            "en-IN"
        )}`;

}